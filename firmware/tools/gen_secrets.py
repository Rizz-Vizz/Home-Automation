#!/usr/bin/env python3
"""Generate the shared master secret for firmware and gateway, plus login PINs.

Writes firmware/src/elly_secret.h and gateway/.env (both gitignored).
Re-flash the board after regenerating, because the firmware embeds the master secret.
Usage: python firmware/tools/gen_secrets.py [--force]
"""
import os
import secrets
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HDR = os.path.join(ROOT, "firmware", "src", "elly_secret.h")
ENV = os.path.join(ROOT, "gateway", ".env")
force = "--force" in sys.argv

if (os.path.exists(HDR) or os.path.exists(ENV)) and not force:
    print("Secrets already exist. Use --force to rotate (you must re-flash the board).")
    sys.exit(0)

master = secrets.token_bytes(32)
pins = {"OWNER": "1", "FAMILY": "2", "GUEST": "3"}

with open(HDR, "w") as f:
    f.write("/* generated by tools/gen_secrets.py, do not commit */\n")
    f.write("#ifndef ELLY_SECRET_H_\n#define ELLY_SECRET_H_\n")
    f.write("#define ELLY_MASTER_KEY_BYTES { " + ", ".join("0x%02x" % b for b in master) + " }\n")
    f.write("#endif\n")

with open(ENV, "w") as f:
    f.write("SERIAL_PORT=COM6\nSERIAL_BAUD=115200\nMQTT_PORT=1883\nHTTP_PORT=8080\n")
    f.write("ELLY_MASTER_KEY=%s\n" % master.hex())
    for r, p in pins.items():
        f.write("%s_PIN=%s\n" % (r, p))
    f.write("MQTT_GATEWAY_SECRET=%s\n" % secrets.token_hex(16))
    f.write("DASHBOARD_ORIGINS=http://127.0.0.1:5173,http://localhost:5173\n")
    f.write("DB_PATH=./data/elly.db\nHEARTBEAT_MS=1000\n")
    f.write("# optional: HTTPS for the dashboard API\n# TLS_CERT=./certs/elly.crt\n# TLS_KEY=./certs/elly.key\n")
    f.write("# optional: cloud mirror (HTTPS ingest endpoint) and server-side LLM\n")
    f.write("# CLOUD_SYNC_URL=\n# CLOUD_SYNC_TOKEN=\n# LLM_ENDPOINT=\n# LLM_API_KEY=\n# LLM_MODEL=gpt-4o-mini\n")

print("Wrote", HDR)
print("Wrote", ENV)
print("Login PINs (also in gateway/.env):")
for r, p in pins.items():
    print("  %-6s %s" % (r.lower(), p))
print("Now rebuild and flash the firmware.")
